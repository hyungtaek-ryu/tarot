function buildDeck() {
  const deck = MAJOR_ARCANA.map(([en, ko, up, rev, astro, element, symbols], i) => ({
    id: `major${String(i).padStart(2, "0")}`,
    en, ko, up, rev, astro, element, symbols,
    major: true,
    number: i,
    arcana: "메이저 아르카나",
  }));
  for (const suit of SUITS) {
    RANKS.forEach(([rankEn, rankKo, numerology], i) => {
      const [up, rev, symbols] = MINOR_DATA[suit.key][i];
      deck.push({
        id: `${suit.key}${String(i + 1).padStart(2, "0")}`,
        en: `${rankEn} of ${suit.en}`,
        ko: `${suit.ko} ${rankKo}`,
        up, rev, symbols, numerology,
        major: false,
        suit: suit.key,
        rank: i + 1,           // 1~10, 11 페이지, 12 나이트, 13 퀸, 14 킹
        court: i >= 10,
        element: suit.element,
        arcana: `마이너 아르카나 · ${suit.ko}(${ELEMENTS[suit.element].ko})`,
      });
    });
  }
  return deck.map((c) => ({ ...c, img: `cards/${c.id}.jpg` }));
}

